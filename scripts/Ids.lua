-- Names -> small integer ids (README, "IDs"). gen/ids.lua is generated at build time by tools/ids/genids.lua from
-- every game's genome tree, so scripts keep writing names (anim:set("walk"), Scene.go("house"),
-- Sound.play("coin")) and the engine resolves each once, at load, then works with ids (bicycle::map, arrays).
--   Ids.get( kind, name )     the id of a name scripts use; an unknown name is an error that lists the known ones
--   Ids.define( kind, name )  the id of a name an asset brings (an Aseprite tag, a scene's spawn). In dev, a name
--                             exported after the last build gets the next free id (with a "rebuild" warning) so
--                             you can keep working; in release builds the generated ids are complete.
--   Ids.name( kind, id )      the name of an id (debugging)
require( "bicycle" )
local Ids = {}

local ok, gen = pcall( require, "gen.ids" )
if not ok or type( gen ) ~= "table" then
  error( "bicycle: no gen/ids.lua (generated by the build from the genome trees: build once with cmake)\n" ..
         tostring( gen ), 0 )
end
Ids.gen = gen
local release = ffi.C.isReleaseBuild()
local warned = {}

local function kindOf( kind )
  local t = gen[kind]
  if not t then error( "Ids: no id kind '" .. tostring( kind ) .. "'", 3 ) end
  gen.names[kind] = gen.names[kind] or {}
  return t, gen.names[kind]
end

local function known( kind )
  local list = {}
  for name in pairs( gen[kind] ) do list[#list + 1] = name end
  table.sort( list )
  return table.concat( list, ", " )
end

function Ids.get( kind, name )
  local t = kindOf( kind )
  local id = t[name]
  if id then return id end
  if type( name ) == "number" and gen.names[kind][name] then return name end  -- already an id
  error( "unknown " .. kind .. " '" .. tostring( name ) .. "' (known: " .. known( kind ) .. ")" ..
         ( release and "" or "; if you just added it to an asset, rebuild so gen/ids.lua has it" ), 2 )
end

-- Like get, but nil instead of an error.
function Ids.find( kind, name ) return kindOf( kind )[name] end

function Ids.define( kind, name )
  local t, names = kindOf( kind )
  local id = t[name]
  if id then return id end
  if release then
    error( kind .. " '" .. tostring( name ) .. "' isn't in the generated ids (gen/ids.lua); the build should have made it", 2 )
  end
  id = 0
  while names[id] ~= nil do id = id + 1 end
  if id > 255 then error( "Ids: more than 256 " .. kind .. " names", 2 ) end
  t[name], names[id] = id, name
  if not warned[kind .. name] then
    warned[kind .. name] = true
    io.stderr:write( "bicycle: " .. kind .. " '" .. tostring( name ) .. "' is newer than gen/ids.lua; rebuild to regenerate it\n" )
  end
  return id
end

function Ids.name( kind, id ) return ( gen.names[kind] or {} )[id] end

return Ids
